#!/usr/bin/env python3
"""make-ui-icons.py — rasterise the interface icons into one 8-bit alpha C header.

    python3 scripts/make-ui-icons.py > TigerTagSplashESP32/ui_icons.h

Sources are the SVG files in svg/ui/ (24x24 stroke icons from the design mockups) and
assets/tigersystem_icon.svg (the Tiger System logo, white tiger on a black square: the
luminance becomes the alpha channel). Each icon becomes a LV_IMG_CF_ALPHA_8BIT image, so
the firmware recolours it per state with lv_obj_set_style_img_recolor() and one bitmap
serves every colour.

Development-time only: it needs ImageMagick (`convert`, which has a built-in SVG
renderer) and Pillow. The generated header is committed, so a normal build needs neither.
Rendering is done at 8x and averaged down, which is what makes thin strokes look smooth
on a 480x320 panel.
"""
import os, re, subprocess, sys, tempfile
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# (name, svg path relative to ROOT, pixel size, kind)  kind: stroke = use alpha, logo = use luminance
ICONS = [
    ("reader",   "svg/ui/reader.svg",   18, "stroke"),
    ("read",     "svg/ui/read.svg",     20, "stroke"),
    ("link",     "svg/ui/link.svg",     20, "stroke"),
    ("refresh",  "svg/ui/refresh.svg",  20, "stroke"),
    ("verify",   "svg/ui/verify.svg",   20, "stroke"),
    ("resume",   "svg/ui/resume.svg",   20, "stroke"),
    ("format",   "svg/ui/format.svg",   20, "stroke"),
    ("tigersys", "assets/tigersystem_icon.svg", 30, "logo"),
]
SS = 8


def render(svg, size, kind):
    with tempfile.TemporaryDirectory() as td:
        png = os.path.join(td, "o.png")
        big = size * SS
        vb = float(re.search(r'viewBox="[-\d.]+ [-\d.]+ ([\d.]+)', open(svg).read()).group(1))
        # density scales the SVG's own size (viewBox units at 72 dpi) to the target size
        subprocess.run(["convert", "-background", "none", "-density", "%.2f" % (72.0 * big / vb), svg,
                        "-resize", "%dx%d!" % (big, big), png], check=True)
        im = Image.open(png).convert("RGBA")
    if kind == "logo":
        # Full-colour logo (white tiger on its dark square), clipped to a rounded square.
        flat = Image.new("RGBA", im.size, (0, 12, 15, 255))
        flat.alpha_composite(im)
        rgb = flat.convert("RGB").resize((size, size), Image.LANCZOS)
        mask = Image.new("L", (size * 8, size * 8), 0)
        from PIL import ImageDraw
        ImageDraw.Draw(mask).rounded_rectangle([0, 0, size * 8 - 1, size * 8 - 1], radius=size * 8 * 0.24, fill=255)
        mask = mask.resize((size, size), Image.LANCZOS)
        return rgb, mask
    return im.split()[3].resize((size, size), Image.LANCZOS)


def main():
    out = ["#pragma once",
           "// Auto-generated by scripts/make-ui-icons.py - do not edit by hand.",
           "// 8-bit alpha icons: colour them with lv_obj_set_style_img_recolor(..., 255)."]
    for name, rel, size, kind in ICONS:
        r = render(os.path.join(ROOT, rel), size, kind)
        if kind == "logo":
            rgb, mask = r
            data = []
            for (cr, cg, cb), al in zip(rgb.getdata(), mask.getdata()):
                c565 = ((cr >> 3) << 11) | ((cg >> 2) << 5) | (cb >> 3)
                data += [c565 & 0xFF, c565 >> 8, al]          # native RGB565 (little endian) + alpha
            cf = "LV_IMG_CF_TRUE_COLOR_ALPHA"
        else:
            data = list(r.tobytes())
            cf = "LV_IMG_CF_ALPHA_8BIT"
        out.append("#define UI_ICON_%s_W %d" % (name.upper(), size))
        out.append("#define UI_ICON_%s_H %d" % (name.upper(), size))
        out.append("static const uint8_t gUi_%sMap[%d] = {" % (name, len(data)))
        for i in range(0, len(data), 24):
            out.append(",".join("0x%02X" % v for v in data[i:i + 24]) + ",")
        out.append("};")
        out.append("static const lv_img_dsc_t gUi_%s = {" % name)
        out.append("    { %s, 0, 0, %d, %d }," % (cf, size, size))
        out.append("    %d," % len(data))
        out.append("    gUi_%sMap" % name)
        out.append("};")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
